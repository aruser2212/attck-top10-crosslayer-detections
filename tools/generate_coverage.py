#!/usr/bin/env python3
"""Generate an inventory, keeping declared evidence separate from executed tests."""
from __future__ import annotations

import argparse
from collections import Counter
from importlib.metadata import PackageNotFoundError, version
import json
from pathlib import Path
import re
import subprocess

import yaml

ROOT = Path(__file__).resolve().parents[1]


def inventory(root: Path = ROOT) -> dict:
    rows = []
    for directory in sorted((root / "techniques").iterdir()):
        if not directory.is_dir():
            continue
        cards = [yaml.safe_load(p.read_text(encoding="utf-8"))
                 for p in sorted(directory.glob("DET-*.yaml"))]
        sigma_files = sorted(path for path in (directory / "sigma").glob("*")
                             if path.suffix in {".yml", ".yaml"})
        network_files = sorted((directory / "network").glob("*.rules"))
        rows.append({
            "technique": directory.name,
            "attack_ids": sorted({t for c in cards for t in c["techniques"]}),
            "detcards": len(cards),
            "sigma_files": len(sigma_files),
            "sigma_rules": sum(sum(d is not None for d in yaml.safe_load_all(p.read_text(encoding="utf-8"))) for p in sigma_files),
            "hunts": len(list((directory / "hunts").glob("*.hunt.yaml"))),
            "network_files": len(network_files),
            "network_rules": sum(len(re.findall(r"\bsid\s*:\s*\d+\s*;", p.read_text(encoding="utf-8"))) for p in network_files),
            "yara": len(list((directory / "yara").glob("*.yara"))),
            "test_plans": int((directory / "tests" / "plan.md").is_file()),
            "lifecycle": dict(sorted(Counter(c["status"] for c in cards).items())),
            "validation": dict(sorted(Counter(c.get("validation", {}).get("status", "not_tested") for c in cards).items())),
            "cards": [{"id": c["id"], "techniques": c["techniques"],
                       "datasets": c.get("tests", {}).get("datasets", [])} for c in cards],
        })
    keys = ("detcards", "sigma_files", "sigma_rules", "hunts", "network_files", "network_rules", "yara", "test_plans")
    return {"technique_folders": len(rows), "totals": {k: sum(row[k] for row in rows) for k in keys}, "techniques": rows}


def markdown(data: dict) -> str:
    lines = ["# Coverage Matrix", "", "Generated by `python tools/generate_coverage.py`. Do not edit the tables manually.", "",
             "This is an inventory and a record of **declared** evidence. A test plan is not an executed test. "
             "`partial` means the linked evidence covers only a documented subset; it is not a production accuracy claim. "
             "Executed checks and versions are captured in CI artifacts; see [validation](validation_report.md).", "",
             "| Technique folder | DetCards | Sigma rules (files) | Hunts | IDPS rules (files) | YARA | Plans | Declared validation |",
             "|---|---:|---:|---:|---:|---:|---:|---|"]
    for row in data["techniques"]:
        states = ", ".join(f"{key}: {value}" for key, value in row["validation"].items())
        lines.append(f"| `{row['technique']}` | {row['detcards']} | {row['sigma_rules']} ({row['sigma_files']}) | {row['hunts']} | {row['network_rules']} ({row['network_files']}) | {row['yara']} | {row['test_plans']} | {states} |")
    t = data["totals"]
    lines.extend(["", f"Totals: **{data['technique_folders']} folders, {t['detcards']} DetCards, {t['sigma_rules']} Sigma rules, {t['hunts']} Hunts, {t['network_rules']} IDPS rules, {t['yara']} YARA rules**.", "", "## Detection IDs and declared datasets", ""])
    for row in data["techniques"]:
        for card in row["cards"]:
            lines.append(f"- `{card['id']}` — {', '.join(card['techniques'])}; {len(card['datasets'])} dataset reference(s).")
    lines.extend(["", "Lifecycle gates, ATT&CK selection and validation limits are defined in [methodology](methodology.md).", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed coverage differs from inventory")
    parser.add_argument("--json-output", type=Path, help="Write runtime inventory with commit and installed tool versions")
    args = parser.parse_args()
    data = inventory()
    output = markdown(data)
    target = ROOT / "docs" / "coverage.md"
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != output:
            print("Coverage is stale. Run python tools/generate_coverage.py")
            return 1
    else:
        target.write_text(output, encoding="utf-8")
    if args.json_output:
        metadata = {}
        for name in ("PyYAML", "jsonschema", "pysigma", "pytest", "yara-python", "scapy"):
            try:
                metadata[name] = version(name)
            except PackageNotFoundError:
                metadata[name] = "not installed"
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True, check=True).stdout)
        args.json_output.parent.mkdir(parents=True, exist_ok=True)
        args.json_output.write_text(json.dumps({"commit": commit, "working_tree_dirty": dirty, "tool_versions": metadata, "inventory": data}, indent=2) + "\n", encoding="utf-8")
    print(f"OK: inventory covers {data['totals']['detcards']} DetCards, {data['totals']['sigma_rules']} Sigma rules and {data['totals']['network_rules']} IDPS signatures.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
